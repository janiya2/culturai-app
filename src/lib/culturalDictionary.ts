/**
 * High-performance search & autocomplete engine
 * Queries both local 250+ entity dictionary and ranks by match relevance.
 */
export function searchCulturalEntities(
  query: string,
  domainFilter?: "music" | "cinema" | "dining" | "fashion" | "travel" | "all"
): CulturalSuggestion[] {
  const cleanQ = query.trim().toLowerCase();
  if (!cleanQ) return [];

  return COMPREHENSIVE_CULTURAL_DICTIONARY.filter((item) => {
    if (domainFilter && domainFilter !== "all" && item.domain !== domainFilter) {
      return false;
    }

    const nameMatch = item.name.toLowerCase().includes(cleanQ);
    const categoryMatch = item.category.toLowerCase().includes(cleanQ);
    const tagsMatch = item.tags.some((t) => t.toLowerCase().includes(cleanQ));
    const subtextMatch = item.subtext.toLowerCase().includes(cleanQ);

    return nameMatch || categoryMatch || tagsMatch || subtextMatch;
  }).sort((a, b) => {
    // Exact startsWith prefix match gets highest priority
    const aStartsWith = a.name.toLowerCase().startsWith(cleanQ);
    const bStartsWith = b.name.toLowerCase().startsWith(cleanQ);
    if (aStartsWith && !bStartsWith) return -1;
    if (!aStartsWith && bStartsWith) return 1;

    // Substring match in name
    const aInName = a.name.toLowerCase().includes(cleanQ);
    const bInName = b.name.toLowerCase().includes(cleanQ);
    if (aInName && !bInName) return -1;
    if (!aInName && bInName) return 1;

    return a.name.localeCompare(b.name);
  }).slice(0, 8); // Top 8 most relevant suggestions
}
